-- Tracker workflow schema parity (2026-11-06)
-- Additive, idempotent; no DROP, TRUNCATE or data modification.
-- Shared across every Tracker client, page and sitemap import.
BEGIN;
CREATE TABLE IF NOT EXISTS public.tracker_workflow_client_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracker_client_id BIGINT NOT NULL REFERENCES public.tracker_clients(id),
  event_type TEXT NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  event_data JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT tracker_workflow_client_event_tracker_client_id_idempotency_key
    UNIQUE (tracker_client_id, idempotency_key)
);
CREATE TABLE IF NOT EXISTS public.tracker_workflow_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracker_client_id BIGINT NOT NULL REFERENCES public.tracker_clients(id),
  tracker_page_id BIGINT NOT NULL REFERENCES public.tracker_pages(id),
  event_type TEXT NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  event_data JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT tracker_workflow_events_tracker_client_id_tracker_page_id_i_key
    UNIQUE (tracker_client_id, tracker_page_id, idempotency_key)
);
CREATE TABLE IF NOT EXISTS public.tracker_workflow_sitemap_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracker_client_id BIGINT NOT NULL REFERENCES public.tracker_clients(id),
  idempotency_key VARCHAR(128) NOT NULL,
  snapshot_hash CHAR(64) NOT NULL,
  event_payload JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT tracker_workflow_sitemap_even_tracker_client_id_idempotency_key
    UNIQUE (tracker_client_id, idempotency_key)
);
-- Fail visibly if a preexisting table is incompatible; CREATE IF NOT EXISTS alone is insufficient.
DO $$
DECLARE actual INTEGER;
BEGIN
  SELECT count(*) INTO actual FROM information_schema.columns
  WHERE table_schema='public' AND table_name='tracker_workflow_client_events'
    AND is_nullable='NO';
  IF actual <> 5 THEN
    RAISE EXCEPTION 'tracker_workflow_client_events required columns mismatch: % not-null columns', actual;
  END IF;
  SELECT count(*) INTO actual FROM information_schema.columns
  WHERE table_schema='public' AND table_name='tracker_workflow_events'
    AND is_nullable='NO';
  IF actual <> 6 THEN
    RAISE EXCEPTION 'tracker_workflow_events required columns mismatch: % not-null columns', actual;
  END IF;
  SELECT count(*) INTO actual FROM information_schema.columns
  WHERE table_schema='public' AND table_name='tracker_workflow_sitemap_events'
    AND is_nullable='NO';
  IF actual <> 5 THEN
    RAISE EXCEPTION 'tracker_workflow_sitemap_events required columns mismatch: % not-null columns', actual;
  END IF;
END $$;
COMMIT;
