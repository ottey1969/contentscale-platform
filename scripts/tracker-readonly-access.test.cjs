'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {patch,anchor,changed}=require('./fix-tracker-readonly-access.cjs');
const original=fs.readFileSync(path.resolve(__dirname,'../src/index.js'),'utf8');
const one=patch(original),two=patch(one.source);
assert.equal(two.changed,false,'patch must be idempotent');
assert.equal(two.source,one.source);
const from=one.source.indexOf(anchor);
const to=one.source.indexOf("app.get('/api/tracker-client/:token/briefs/:pageId'",from);
const route=one.source.slice(from,to);
assert(route.includes(changed),'client read API must accept a real read-only share token');
assert(route.includes("cr.rows[0].status === 'disabled' || cr.rows[0].status === 'paused'"),'disabled/paused status must remain blocked');
assert(!route.includes('if (!client.gsc_enabled)'),'GSC cannot gate opening the Tracker');
assert(one.source.includes("app.get('/track/:token',"),'real client page route retained');
assert(one.source.includes("client.readonly_token && client.readonly_token === req.params.token"),'read-only display semantics retained');
const before=original.indexOf(anchor),beforeEnd=original.indexOf("app.get('/api/tracker-client/:token/briefs/:pageId'",before);
assert.equal(one.source.slice(0,from),original.slice(0,before));
assert.equal(one.source.slice(to),original.slice(beforeEnd),'no other GET, POST, GSC, or admin route may change');
console.log('PASS: main and read-only client tokens share GET access; status guard and all write routes unchanged');
