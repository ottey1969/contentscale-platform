'use strict';
const assert=require('node:assert/strict');
const {decideGrowthEditorialAction}=require('./growth-editorial-decision-gate.cjs');
const report={url:'https://site.example/',growth_decision:{primary_next_action:{query:'content scaling',metrics:{impressions:3943,clicks:2}},protection:{case_study_locked:true}}};
const base={target_url:'https://site.example/content-at-scale/',status:'FULL_SECTION_COMPARISON_RESEARCH_ONLY'};
const missing=decideGrowthEditorialAction({report,destination:{status:'EXISTING_DESTINATION_EVIDENCE_UNAVAILABLE'}});
assert.equal(missing.decision,'DATA_BLOCKED');
assert.equal(missing.publish_allowed,false);
const unrelated=decideGrowthEditorialAction({report,destination:{...base,comparisons:[{competitor_url:'https://rival.example/',match_status:'NO_RELIABLE_SECTION_MATCH',nearest_existing_section:null}]}});
assert.equal(unrelated.decision,'DATA_BLOCKED');
assert.equal(unrelated.verified_gap,false);
const related=decideGrowthEditorialAction({report,destination:{...base,comparisons:[{competitor_url:'https://rival.example/',competitor_heading:'Content scaling process',match_status:'POSSIBLE_TOPICAL_MATCH_REVIEW_REQUIRED',nearest_existing_section:{heading:'Our content scaling process'}}]}});
assert.equal(related.decision,'DATA_BLOCKED','lexical overlap alone never verifies a content gap');
assert.equal(related.blocker_code,'SUBSTANTIVE_GAP_NOT_VERIFIED');
assert.equal(related.strongest_comparison.own_heading,'Our content scaling process');
assert.equal(related.case_study_locked,true);
assert.equal(related.copy_ready,false);
assert.equal(related.publish_allowed,false);
const noMetrics=decideGrowthEditorialAction({report:{...report,growth_decision:{primary_next_action:{query:'content scaling'}}},destination:base});
assert.equal(noMetrics.decision,'DATA_BLOCKED');
console.log('PASS Growth explicit editorial decision with no fabricated gap or Case Study writes');
