function extractDomainFromUrl(url) {
if (!url) return 'Bedrijf';
try {
const hostname = new URL(url).hostname;
let domain = hostname.replace('www.', '');
let name = domain.split('.')[0];
return name.charAt(0).toUpperCase() + name.slice(1);
} catch (e) {
return 'Bedrijf';
}
}

