'use strict';
const assert=require('node:assert/strict');
const {planIntentToRevenue}=require('./growth-intent-revenue.cjs');
const base={canonicalUrl:'https://demo.example/aeo-vs-geo-vs-seo/',title:'AEO vs GEO vs SEO',query:'AEO vs GEO vs SEO',evidenceScope:'observed'};
const offers={ai_visibility:{url:'https://demo.example/ai-visibility-check/',available:true,claimsVerified:true}};
const x=planIntentToRevenue({...base,offers});
assert.equal(x.status,'READY_FOR_EDITOR');
assert.equal(x.match,'ai_visibility');
assert.equal(x.auto_publish,false);
assert(x.html.includes('data-growth-cta="growth-ai_visibility"'));
assert(x.measurement.events.includes('qualified_lead'));
assert.equal(planIntentToRevenue(base).status,'NEEDS_EVIDENCE');
assert.equal(planIntentToRevenue({...base,offers:{ai_visibility:{...offers.ai_visibility,available:false}}}).status,'BLOCKED');
assert.equal(planIntentToRevenue({...base,offers:{ai_visibility:{...offers.ai_visibility,url:'javascript:alert(1)'}}}).status,'BLOCKED');
assert.equal(planIntentToRevenue({...base,offers:{ai_visibility:{...offers.ai_visibility,url:'https://evil.example/landing/'}}}).status,'BLOCKED');
assert.equal(planIntentToRevenue({...base,offers:{ai_visibility:{...offers.ai_visibility,claimsVerified:false}}}).status,'NEEDS_EVIDENCE');
assert.equal(planIntentToRevenue({...base,query:'best banana',title:'Banana facts',offers}).status,'NEEDS_EVIDENCE');
let r=planIntentToRevenue({canonicalUrl:'https://roof.example/roof-leak/',title:'What causes a roof leak?',query:'how to stop roof leaks',offers:{roof_leak:{url:'https://roof.example/inspection/',available:true,claimsVerified:true}}});
assert.equal(r.match,'roof_leak');assert.equal(r.status,'READY_FOR_EDITOR');
console.log('growth intent revenue: tests passed');
