'use strict';
const assert=require('node:assert/strict');
const {buildGrowthEditInstructions}=require('./growth-edit-instructions.cjs');
const url='https://contentscale.site/page/';
const good={target_url:url,source_url:'https://competitor.example/article',observed:'A sourced FAQ is present',improvement:'Add a factual FAQ using verified first-party answers',where_in_draft:'FAQ',retrieved_at:'2026-10-12T00:00:00Z'};
let x=buildGrowthEditInstructions({page:{url},searchSpy:[good],aiSpy:[]});
assert.equal(x.status,'PROPOSED_FOR_EDITOR_REVIEW');
assert.equal(x.instructions.length,1);
assert.equal(x.instructions[0].status,'PROPOSED_NOT_APPLIED');
assert.equal(x.instructions[0].click_uplift_estimate,null);
assert.equal(x.auto_publish,false);
x=buildGrowthEditInstructions({page:{url},searchSpy:[{...good,target_url:'https://wrong.example/'}],aiSpy:[]});
assert.equal(x.status,'BLOCKED');
assert.equal(x.instructions.length,0);
x=buildGrowthEditInstructions({page:{url,case_study_active:true},searchSpy:[good],aiSpy:[]});
assert(x.issues.includes('CASE_STUDY_LOCK'));
x=buildGrowthEditInstructions({page:{url},searchSpy:[{...good,source_url:'https://www.contentscale.site/other/'}],aiSpy:[]});
assert.equal(x.instructions.length,0);
console.log('PASS: source-backed Growth edit instructions remain proposals');
