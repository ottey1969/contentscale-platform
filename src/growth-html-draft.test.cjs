'use strict';
const assert=require('node:assert/strict');
const {assembleGrowthHtmlDraft}=require('./growth-html-draft.cjs');
const original='<article class="approved"><h1>Old</h1><img src="/old.jpg" alt="old"></article>';
let x=assembleGrowthHtmlDraft({originalHtml:original,additions:[{approved:true,evidence_ref:'verified:123',html:'<section><h2>New guidance</h2><p>Editor verified content.</p></section>'}]});
assert.equal(x.status,'DRAFT_FOR_REVIEW');
assert.equal(x.inserted,1);
assert(x.html.includes('<img src="/old.jpg" alt="old">'));
assert(x.html.startsWith(original.slice(0,original.indexOf('</article>'))));
assert(x.html.includes('<section><h2>New guidance</h2>'));
x=assembleGrowthHtmlDraft({originalHtml:original,additions:[{approved:false,html:'<p>Unapproved</p>'}]});
assert.equal(x.status,'NO_APPROVED_EDITS');assert.equal(x.html,original);
x=assembleGrowthHtmlDraft({originalHtml:original,caseStudyLocked:true});
assert.equal(x.status,'BLOCKED');assert.equal(x.html,null);
x=assembleGrowthHtmlDraft({originalHtml:original,additions:[{approved:true,evidence_ref:'x',html:'<script>alert(1)</script>'}]});
assert(x.issues.includes('UNSAFE_ADDITION_HTML'));
x=assembleGrowthHtmlDraft({originalHtml:'<div>not article</div>',additions:[{approved:true,evidence_ref:'x',html:'<p>New</p>'}]});
assert(x.issues.includes('ARTICLE_BOUNDARY_NOT_FOUND'));
console.log('PASS: editor-approved HTML additions preserve original article');
