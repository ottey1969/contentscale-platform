'use strict';
const assert=require('node:assert/strict');
const {inspectSavedGrowthHtml,LIMIT}=require('../src/tracker-growth-snapshot-signals.cjs');
const {registerGrowthCockpit}=require('../src/tracker-growth-cockpit.cjs');
const html='<!doctype html><html><head><title>Actual title</title><meta name="description" content="A real existing page about roofing repairs"><link rel="canonical" href="https://roofer.example/roof/"></head><body><h1>Roof repair in town</h1><h2>What is included?</h2><p>These facts require verification before changing the current page.</p><a href="/services/">Related service</a><a href="https://external.example/article">External</a><img src="/photo.jpg"></body></html>';
const sig=inspectSavedGrowthHtml(html,'https://roofer.example/roof/');
assert.equal(sig.available,true);
assert.equal(sig.live_verified,false);
assert.equal(sig.title_observed,true);
assert.equal(sig.h1_count_observed,1);
assert.equal(sig.h2_count_observed,1);
assert.equal(sig.meta_description_observed,true);
assert.equal(sig.canonical_tag_observed,true);
assert.equal(sig.internal_links_observed,1);
assert.equal(sig.external_links_observed,1);
assert.equal(sig.images_missing_alt_observed,1);
assert(sig.approx_excerpt_words>7);
const no=inspectSavedGrowthHtml(null,'https://roofer.example/roof/');
assert.equal(no.available,false);
assert.equal(no.h1_count_observed,undefined,'Do not claim zero headings without source');
const deceptive=inspectSavedGrowthHtml('<script><h1>Fake</h1></script><style><h2>Fake</h2></style><h1>Real</h1>','https://roofer.example/');
assert.equal(deceptive.h1_count_observed,1);
assert.equal(deceptive.h2_count_observed,0);
const big=inspectSavedGrowthHtml(html+' '.repeat(LIMIT+50),'https://roofer.example/roof/');
assert.equal(big.excerpt_truncated,true);
const routes={},queries=[],pages=[{id:5,url:'https://roofer.example/roof/',keyword:'roof repair',gsc_impressions:null,gsc_clicks:null,gsc_position:null,brief_content:null,case_study_active:false}];
registerGrowthCockpit({get(p,...handlers){routes[p]=handlers}},{
 async query(sql,args){queries.push({sql,args});
  if(sql.includes('FROM tracker_clients'))return{rows:[{id:7,domain:'roofer.example',status:'active',token:'owner-token'}]};
  if(sql.includes('FROM tracker_pages p'))return{rows:pages};
  if(sql.includes('FROM tracker_gsc_queries q'))throw Object.assign(Error('GSC not connected'),{code:'42P01'});
  if(sql.includes('LEFT(html_content'))return{rows:[{saved_html:html,excerpt_truncated:false}]};
  throw Error('Unexpected SQL');
 }});
(async()=>{
 const handlers=routes['/api/tracker-client/:token/growth/research-brief'];
 const req={params:{token:'shared-readonly'},query:{page_id:'5'}};
 const res={statusCode:200,status(v){this.statusCode=v;return this},type(){return this},set(){return this},send(v){this.body=v;return this}};
 await handlers[0](req,res,()=>handlers[1](req,res));
 assert.equal(res.statusCode,200);
 assert.match(res.body,/OBSERVED HISTORICAL EXCERPT, NOT VERIFIED LIVE/);
 assert.match(res.body,/H1 count observed: 1; H2 count observed: 1/);
 assert.match(res.body,/Links observed: 1 internal, 1 external/);
 assert.match(res.body,/NO GSC REQUIRED/);
 assert.match(res.body,/No competitor findings, Google positions or click uplift are claimed as verified/);
 const sourceQuery=queries.find(q=>q.sql.includes('LEFT(html_content'));
 assert.deepEqual(sourceQuery.args,[7,5]);
 assert(!queries.some(q=>/^\s*(INSERT|DELETE|UPDATE)/i.test(q.sql)),'No DB mutation');
 console.log('PASS bounded saved-HTML Growth signals, source-only page identity, no GSC dependency, no invented live evidence');
})().catch(e=>{console.error(e);process.exitCode=1});
