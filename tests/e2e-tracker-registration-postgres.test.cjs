'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { randomBytes } = require('node:crypto');

const database = process.env.DATABASE_URL || '';
const isolated = /^postgres(?:ql)?:\/\/[^@]+@(?:127\.0\.0\.1|localhost):\d+\/(?:test\w*|\w+_e2e)$/.test(database);

test('Tracker registration returns the committed account and serializes duplicate requests', {
  skip: !isolated && 'requires disposable local PostgreSQL'
}, async () => {
  const { Pool } = require('pg');
  const schema = 'tracker_registration_' + randomBytes(8).toString('hex');
  const control = new Pool({ connectionString: database, max: 1 });
  const pool = new Pool({ connectionString: database, options: '-c search_path=' + schema, max: 6 });
  try {
    await control.query('CREATE SCHEMA ' + schema);
    await pool.query(`CREATE TABLE tracker_clients (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token TEXT UNIQUE, domain TEXT, name TEXT,
      email TEXT, whatsapp TEXT, max_pages INT, registered_ip TEXT, dealify_codes TEXT,
      gsc_enabled BOOLEAN, live_wall_enabled BOOLEAN, status TEXT
    );
    CREATE TABLE tracker_pages (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tracker_client_id INT, url TEXT,
      check_frequency TEXT, next_check_at TIMESTAMPTZ, email_reminders BOOLEAN, next_ai_reminder_at TIMESTAMPTZ);
    CREATE TABLE tracker_case_studies (id INT, tracker_client_id INT, tracker_page_id INT);
    CREATE TABLE tracker_case_study_events (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      case_study_id INT NOT NULL, tracker_page_id INT, event_type TEXT, source TEXT, event_data JSONB,
      event_at TIMESTAMPTZ DEFAULT NOW());
    CREATE TABLE prospect_quick_scans (id BIGINT PRIMARY KEY, token TEXT, url TEXT, scan_result JSONB,
      scan_completed_at TIMESTAMPTZ, revoked_at TIMESTAMPTZ, tracker_interested BOOLEAN, follow_up_status TEXT, audit20_status TEXT)`);
    const source = fs.readFileSync(require.resolve('../src/index.js'), 'utf8');
    const start = source.indexOf("app.post('/api/tracker-client/register',");
    const end = source.indexOf('// CONTENTSCALE-CASE-STUDY-PHASE1', start);
    assert.ok(start >= 0 && end > start);
    const app = require('express')();
    app.use(require('express').json());
    const notices = [];
    vm.runInNewContext(source.slice(start, end), {
      app, pool, require: require('node:module').createRequire(require.resolve('../src/index.js')),
      _ensureProspectQuickScanTable: async () => true,
      _ensureCaseStudySchema: async () => true,
      process: { env: { APP_URL: 'https://tracker.example' } },
      generateClientToken: () => randomBytes(24).toString('hex'),
      notifyOttmar: async subject => { notices.push(subject); },
      sendTrackerEmail: async () => {}
    });
    const api = require('supertest')(app);
    const register = (domain, ip, dealify_code) =>
      api.post('/api/tracker-client/register').set('X-Forwarded-For', ip).send({ domain, name: 'Verified fixture', dealify_code });
    const free = await register('free.example', '192.0.2.1').expect(200);
    assert.match(free.body.url, /https:\/\/tracker\.example\/track\/[a-f0-9]+$/);
    const paid = await register('paid.example', '192.0.2.1', 'DEALIFY-TEST').expect(200);
    assert.equal(paid.body.max_pages, 10);

    const concurrent = await Promise.all([
      register('parallel.example', '192.0.2.2'), register('https://www.parallel.example/page', '192.0.2.3')
    ]);
    assert.deepEqual(concurrent.map(response => response.status).sort(), [200, 409]);
    assert.equal(concurrent.find(response => response.status === 409).body.token, undefined);
    const sameIp = await Promise.all([register('one.example', '192.0.2.4'), register('two.example', '192.0.2.4')]);
    assert.deepEqual(sameIp.map(response => response.status).sort(), [200, 429]);
    assert.equal((await pool.query("SELECT count(*)::int AS n FROM tracker_clients WHERE domain='parallel.example'")).rows[0].n, 1);
    assert.equal((await pool.query('SELECT count(*)::int AS n FROM tracker_clients')).rows[0].n, 4);
    assert.equal(notices.filter(subject => subject.includes('New tracker:')).length, 4);

    const prospectPage = 'https://www.prospect.example/Services/?view=full';
    const prospectKey = '12'.repeat(32);
    const prospectResult = { score: 0, url: prospectPage };
    await pool.query(`INSERT INTO prospect_quick_scans VALUES (1,$1,$2,$3,NOW(),NULL,TRUE,'replied','not_started')`,
      [prospectKey, prospectPage, prospectResult]);
    const registerProspect = (domain, key) => api.post('/api/tracker-client/register').set('X-Forwarded-For', '192.0.2.5')
      .send({ domain, name: 'Prospect fixture', quick_scan_key: key });
    await registerProspect('prospect.example', prospectKey).expect(404);
    await pool.query("UPDATE prospect_quick_scans SET audit20_status='ready' WHERE id=1");
    await registerProspect('other.example', prospectKey).expect(404);
    await pool.query('UPDATE prospect_quick_scans SET tracker_interested=FALSE WHERE id=1');
    await registerProspect('prospect.example', prospectKey).expect(404);
    await pool.query('UPDATE prospect_quick_scans SET tracker_interested=TRUE WHERE id=1');
    const converted = await registerProspect('prospect.example', prospectKey).expect(200);
    const proof = require('../src/tracker-proof-sources.cjs');
    const page = (await pool.query('SELECT * FROM tracker_pages')).rows[0];
    assert.equal(converted.body.linked_page_id, page.id);
    assert.equal(page.url, prospectPage);
    assert.equal(page.check_frequency, '0');
    assert.equal(page.next_check_at, null);
    assert.equal(page.email_reminders, false);
    assert.equal((await proof.loadPageProofSources(pool,page)).quick_scan[0].score, 0);
    await registerProspect('prospect.example', prospectKey).expect(409);
    assert.equal((await pool.query('SELECT count(*)::int AS n FROM tracker_pages')).rows[0].n, 1);
    assert.deepEqual((await pool.query('SELECT scan_result,follow_up_status FROM prospect_quick_scans WHERE id=1')).rows[0],
      { scan_result: prospectResult, follow_up_status: 'replied' });
  } finally {
    await pool.end();
    await control.query('DROP SCHEMA IF EXISTS ' + schema + ' CASCADE');
    await control.end();
  }
});
